def kabsch_umeyama(A, B):
    assert A.shape == B.shape
    n, m = A.shape

    EA = np.mean(A, axis=0)
    EB = np.mean(B, axis=0)
    VarA = np.mean(np.linalg.norm(A - EA, axis=1) ** 2)

    H = ((A - EA).T @ (B - EB)) / n
    U, D, VT = np.linalg.svd(H)
    d = np.sign(np.linalg.det(U) * np.linalg.det(VT))
    S = np.diag([1] * (m - 1) + [d])

    R = U @ S @ VT
    c = VarA / np.trace(np.diag(D) @ S)
    t = EA - c * R @ EB

    return R, c, t

def kabsch_umeyama_rmse(A, B):
    assert A.shape == B.shape

    R, c, t = kabsch_umeyama(A, B)

    B_aligned = np.array([
        t + c * R @ b
        for b in B
    ])

    rmse = np.sqrt(np.mean(np.sum((A - B_aligned)**2, axis=1)))

    return rmse

def align(A, B):
    """Return B transformed onto A (target A, source B) as an (n, m) array."""
    R, c, t = kabsch_umeyama(A, B)
    return np.array([t + c * R @ b for b in B])


def point_errors(A, B_aligned):
    """Euclidean distance between each target point and its aligned counterpart."""
    return np.linalg.norm(A - B_aligned, axis=1)


def residual_std(A, B_aligned, ddof=0):
    """Standard deviation of the per-point errors (ddof=1 for the sample standard deviation)."""
    return np.std(point_errors(A, B_aligned), ddof=ddof)


def r_squared(A, B_aligned):
    """R^2 = 1 - SS_res / SS_tot, over every coordinate of every point.
    SS_res = sum of squared residuals, SS_tot = squared spread of the target about its centroid."""
    ss_res = np.sum((A - B_aligned) ** 2)
    ss_tot = np.sum((A - np.mean(A, axis=0)) ** 2)
    return 1.0 - ss_res / ss_tot


def adjusted_r_squared(A, B_aligned, n_params=None):
    """Adjusted R^2 = 1 - (1 - R^2) * (N - 1) / (N - p - 1).
    N = number of scalar observations (n points * m coordinates).
    p = fitted parameters of the similarity transform (rotation + translation + scale):
        m(m-1)/2 + m + 1, which is 7 in 3D. Pass n_params to override."""
    n, m = A.shape
    N = n * m
    p = n_params if n_params is not None else m * (m - 1) // 2 + m + 1
    return 1.0 - (1.0 - r_squared(A, B_aligned)) * (N - 1) / (N - p - 1)


def plot_alignment(A, B_aligned, points_per_mech=6, save=None):
    """3D plot of the target points (A) and the aligned points together.
    Circles = target, X = aligned, thin grey lines = per-point residuals.
    Mechanisms are coloured separately and outlined in vertex order."""
    import matplotlib.pyplot as plt

    colors = ["#4c78a8", "#f58518", "#54a24b", "#b279a2", "#e45756", "#72b7b2"]
    fig = plt.figure(figsize=(10, 8))
    ax = fig.add_subplot(111, projection="3d")

    for k in range(0, len(A), points_per_mech):
        c = colors[(k // points_per_mech) % len(colors)]
        mech = k // points_per_mech
        for P, style, line_color in ((A, "-", "black"), (B_aligned, "-", "orange")):
            Q = P[k:k + points_per_mech]
            loop = np.vstack([Q, Q[:1]])
            ax.plot(loop[:, 0], loop[:, 1], loop[:, 2], style, color=line_color, linewidth=1.3)
        ax.scatter(*A[k:k + points_per_mech].T, color=c, marker="o", s=30, label=f"M{mech} target")
        ax.scatter(*B_aligned[k:k + points_per_mech].T, color=c, marker="x", s=45, label=f"M{mech} aligned")
        for i in range(k, min(k + points_per_mech, len(A))):
            ax.text(A[i, 0], A[i, 1], A[i, 2], f"{i - k}", fontsize=8, color=c)

    for a, b in zip(A, B_aligned):
        ax.plot(*zip(a, b), color="grey", linewidth=0.6, alpha=0.7)

    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.set_zlabel("z")
    ax.set_title("Target (MathL1Theta0, o, solid) vs aligned (AlignedPhysSimCard, x, dotted)")
    ax.legend(fontsize=7, ncol=2, loc="upper left", bbox_to_anchor=(0.0, 0.92))
    # equal axes so the card is not distorted
    allp = np.vstack([A, B_aligned])
    mid, half = allp.mean(axis=0), (allp.max(axis=0) - allp.min(axis=0)).max() / 2
    ax.set_xlim(mid[0] - half, mid[0] + half)
    ax.set_ylim(mid[1] - half, mid[1] + half)
    ax.set_zlim(mid[2] - half, mid[2] + half)
    plt.tight_layout()
    if save:
        fig.savefig(save, dpi=150)
        print("saved", save)
    else:
        plt.show()


